export { canManageJemaat };

export function getFamilyById(familyId) {
  return families.find((family) => family.id === familyId);
}

export function getFamilyMembers(familyId) {
  return individuals.filter((individual) => individual.familyId === familyId);
}

export function getIndependentIndividuals() {
  return individuals.filter((individual) => !individual.familyId);
}

export function getFamilyForIndividual(individual) {
  return individual.familyId ? getFamilyById(individual.familyId) : null;
}

export function getJemaatStats() {
  const activeIndividuals = individuals.filter(
    (individual) => individual.statusJemaat === "Aktif"
  );

  return {
    familyCount: families.length,
    individualCount: individuals.length,
    independentCount: getIndependentIndividuals().length,
    activeCount: activeIndividuals.length,
  };
}

export function getSectorOptions() {
  return [...new Set(families.map((family) => family.sektor))].sort();
}

export function genderInitial(jenisKelamin) {
  return jenisKelamin === "Laki-laki" ? "L" : "P";
}

export function formatDate(value) {
  if (!value) return "-";

  return new Intl.DateTimeFormat("id-ID", {
    day: "numeric",
    month: "long",
    year: "numeric",
  }).format(new Date(`${value}T00:00:00`));
}

export function formatBirthPlaceDate(individual) {
  const date = formatDate(individual.tanggalLahir);
  if (!individual.tempatLahir) return date;
  return `${individual.tempatLahir}, ${date}`;
}
